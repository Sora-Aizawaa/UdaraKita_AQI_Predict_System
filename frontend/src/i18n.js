export const HARI = {
  id: ["Min", "Sen", "Sel", "Rab", "Kam", "Jum", "Sab"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
  ja: ["日", "月", "火", "水", "木", "金", "土"],
};
const BULAN = {
  id: ["Jan", "Feb", "Mar", "Apr", "Mei", "Jun", "Jul", "Agu", "Sep", "Okt", "Nov", "Des"],
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
};

export function terjemah(bahasa, kunci, nilai) {
  const teks = KAMUS[bahasa]?.[kunci] ?? KAMUS.id[kunci] ?? kunci;
  if (!nilai) return teks;
  return teks.replace(/\{(\w+)\}/g, (_, k) => (nilai[k] ?? `{${k}}`));
}

const dua = (n) => String(n).padStart(2, "0");

/** "2026-02-18T15:00" -> "18 Feb, 15.00" / "18 Feb, 15:00" / "2月18日 15:00" (jam lokal kota, tanpa konversi zona waktu). */
export function formatWaktu(iso, bahasa) {
  if (!iso) return "—";
  const [tgl, jam = "00:00"] = iso.split("T");
  const [, m, d] = tgl.split("-").map(Number);
  const [hh, mm] = jam.slice(0, 5).split(":");
  if (bahasa === "ja") return `${m}月${d}日 ${hh}:${mm}`;
  if (bahasa === "en") return `${d} ${BULAN.en[m - 1]}, ${hh}:${mm}`;
  return `${d} ${BULAN.id[m - 1]}, ${hh}.${mm}`;
}

/** "2026-02-18" -> "Rab, 18 Feb" / "Wed, 18 Feb" / "2月18日(水)". */
export function formatTanggal(tgl, bahasa) {
  const [y, m, d] = tgl.split("-").map(Number);
  const hari = HARI[bahasa][new Date(y, m - 1, d).getDay()];
  if (bahasa === "ja") return `${m}月${d}日(${hari})`;
  return `${hari}, ${d} ${BULAN[bahasa][m - 1]}`;
}

/** "2026-02-18 15:00:00" -> "02-18 15:00" */
export function formatSlotBmkg(waktu) {
  return waktu ? waktu.slice(5, 16) : "—";
}

/** Jam untuk strip per jam: "15.00" (ID/JA) atau "15:00" (EN). */
export function formatJam(jam, bahasa) {
  return bahasa === "en" ? jam.replace(".", ":") : jam;
}

export function hariDariIso(iso, bahasa) {
  return HARI[bahasa][new Date(iso).getDay()];
}

